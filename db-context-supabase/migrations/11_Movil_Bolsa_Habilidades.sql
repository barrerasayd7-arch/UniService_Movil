-- PostgreSQL / Supabase. Ejecutar sobre la base existente, nunca schema-full.sql.
-- No modifica ni elimina cuentas o solicitudes anteriores.
BEGIN;

CREATE TABLE IF NOT EXISTS public.identidades_institucionales (
    id_usuario integer PRIMARY KEY REFERENCES public.usuarios(id_usuario) ON DELETE CASCADE,
    tenant_id uuid NOT NULL,
    object_id uuid NOT NULL,
    verificado_hasta timestamptz NOT NULL,
    verificado_en timestamptz NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, object_id)
);

CREATE TABLE IF NOT EXISTS public.habilidades (
    id_habilidad integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(80) NOT NULL UNIQUE CHECK (length(trim(nombre)) >= 2)
);
CREATE TABLE IF NOT EXISTS public.usuario_habilidades (
    id_usuario integer NOT NULL REFERENCES public.usuarios(id_usuario) ON DELETE CASCADE,
    id_habilidad integer NOT NULL REFERENCES public.habilidades(id_habilidad),
    nivel varchar(20) NOT NULL CHECK (nivel IN ('basico', 'intermedio', 'avanzado')),
    detalle varchar(500) NOT NULL DEFAULT '',
    PRIMARY KEY (id_usuario, id_habilidad)
);
CREATE INDEX IF NOT EXISTS ix_usuario_habilidad_matching
    ON public.usuario_habilidades(id_habilidad, id_usuario);

CREATE TABLE IF NOT EXISTS public.peticiones_servicio (
    id_peticion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_autor integer NOT NULL REFERENCES public.usuarios(id_usuario),
    titulo varchar(120) NOT NULL CHECK (length(trim(titulo)) BETWEEN 5 AND 120),
    descripcion varchar(4000) NOT NULL CHECK (length(trim(descripcion)) BETWEEN 20 AND 4000),
    presupuesto numeric(12,2) CHECK (presupuesto >= 0),
    modalidad varchar(20) NOT NULL CHECK (modalidad IN ('virtual', 'presencial', 'mixta')),
    fecha_limite timestamptz NOT NULL,
    estado varchar(20) NOT NULL DEFAULT 'abierta'
        CHECK (estado IN ('abierta', 'asignada', 'completada', 'cancelada')),
    creado_en timestamptz NOT NULL DEFAULT now(),
    CHECK (fecha_limite > creado_en)
);
CREATE INDEX IF NOT EXISTS ix_peticiones_feed ON public.peticiones_servicio(estado, fecha_limite, creado_en DESC);
CREATE INDEX IF NOT EXISTS ix_peticiones_autor ON public.peticiones_servicio(id_autor, creado_en DESC);
CREATE TABLE IF NOT EXISTS public.peticion_habilidades (
    id_peticion integer NOT NULL REFERENCES public.peticiones_servicio(id_peticion) ON DELETE CASCADE,
    id_habilidad integer NOT NULL REFERENCES public.habilidades(id_habilidad),
    PRIMARY KEY (id_peticion, id_habilidad)
);
CREATE INDEX IF NOT EXISTS ix_peticion_habilidad_matching ON public.peticion_habilidades(id_habilidad, id_peticion);

CREATE TABLE IF NOT EXISTS public.postulaciones_servicio (
    id_postulacion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_peticion integer NOT NULL REFERENCES public.peticiones_servicio(id_peticion) ON DELETE CASCADE,
    id_usuario integer NOT NULL REFERENCES public.usuarios(id_usuario),
    mensaje varchar(2000) NOT NULL CHECK (length(trim(mensaje)) BETWEEN 10 AND 2000),
    precio_propuesto numeric(12,2) CHECK (precio_propuesto >= 0),
    estado varchar(20) NOT NULL DEFAULT 'pendiente'
        CHECK (estado IN ('pendiente', 'aceptada', 'rechazada')),
    creado_en timestamptz NOT NULL DEFAULT now(),
    UNIQUE (id_peticion, id_usuario)
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_una_postulacion_aceptada
    ON public.postulaciones_servicio(id_peticion) WHERE estado = 'aceptada';

-- La API .NET usa usuarios integer y JWT propio, no auth.uid() de Supabase.
-- Estas tablas no se exponen al cliente mediante anon/authenticated.
ALTER TABLE public.identidades_institucionales ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.habilidades ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.usuario_habilidades ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.peticiones_servicio ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.peticion_habilidades ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.postulaciones_servicio ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.identidades_institucionales, public.habilidades,
    public.usuario_habilidades, public.peticiones_servicio,
    public.peticion_habilidades, public.postulaciones_servicio FROM anon, authenticated;

